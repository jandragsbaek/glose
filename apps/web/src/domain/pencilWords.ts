export const pencilWordsFor = (language: string): PencilWords | null => {
  const base = language.toLowerCase().split("-")[0] ?? "";
  if (base === "en") return EN;
  if (base === "da" || base === "nb" || base === "no") return base === "da" ? DA : null;
  return null;
};

